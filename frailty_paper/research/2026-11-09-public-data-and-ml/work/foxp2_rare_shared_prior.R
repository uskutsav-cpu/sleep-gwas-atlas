.libPaths(c('work/stage5_Rlib',.libPaths()))
library(coloc)
f<-readRDS('work/stage6_foxp2_gnomad_ancestry_matched_fits.rds')
vals<-c(1e-8,1e-7,1e-6,1e-5,5e-5)
res<-do.call(rbind,lapply(vals,function(p){x<-as.data.frame(coloc.susie(f$MVP_effN,f$HFRS,p1=1e-4,p2=1e-4,p12=p)$summary);x$p12<-p;x}))
original<-read.csv('outputs/stage6_foxp2_gnomad_ancestry_matched_coloc.csv')
old<-subset(original,mvp_n_assumption=='effN' & p12==1e-5)
check<-subset(res,p12==1e-5)
stopifnot(nrow(check)==1,nrow(old)==1,abs(check$PP.H4.abf-old$PP.H4.abf)<1e-10)
write.csv(res,'outputs/stage6_foxp2_low_shared_prior_sensitivity.csv',row.names=FALSE)
print(res[,c('p12','PP.H3.abf','PP.H4.abf')])
