# Exploratory postselected four-gene analysis; not a score validation.
.libPaths(c('work/rna_Rlib',.libPaths())); suppressPackageStartupMessages(library(edgeR))
meta <- readLines(gzfile('work/GSE167186_GPL20301_series_matrix.txt.gz'))
parse_row <- function(line) as.character(read.delim(text=line,header=FALSE,quote='"',check.names=FALSE,stringsAsFactors=FALSE)[1,-1])
titles <- parse_row(meta[grep('^!Sample_title\t',meta)])
chars <- lapply(meta[grep('^!Sample_characteristics_ch1\t',meta)],parse_row)
groups <- Filter(function(x) all(startsWith(x,'group: ')),chars); ages <- Filter(function(x) all(startsWith(x,'age: ')),chars)
stopifnot(length(groups)==1,length(ages)==1,length(titles)==76,!anyDuplicated(titles))
group <- sub('^group: ','',groups[[1]]); age <- as.numeric(sub('^age: ','',ages[[1]]))
counts <- read.csv(gzfile('work/GSE167186_counts.csv.gz'),check.names=FALSE)
stopifnot(identical(names(counts)[-1],titles),all(is.finite(age)),!anyNA(counts[,-1]),all(as.matrix(counts[,-1])>=0))
keep <- group %in% c('Old Healthy','Sarcopenia'); stopifnot(sum(keep)==53,sum(group=='Old Healthy')==29,sum(group=='Sarcopenia')==24)
raw <- as.matrix(counts[,-1])[,keep]; rownames(raw)<-make.unique(as.character(counts$Symbol)); storage.mode(raw)<-'numeric'
condition <- as.numeric(group[keep]=='Sarcopenia'); age <- age[keep];design <- model.matrix(~condition+age)
y <- DGEList(counts=raw); ok<-filterByExpr(y,design=design); y<-y[ok,,keep.lib.sizes=FALSE]; y<-calcNormFactors(y,method='TMM')
y<-estimateDisp(y,design,robust=TRUE); fit<-glmQLFit(y,design,robust=TRUE);res<-glmQLFTest(fit,coef='condition')
target<-c('FOXP2','SMAD5','RBM6','MEIS1');stopifnot(all(vapply(target,function(g) sum(counts$Symbol==g)==1,logical(1))))
alltab<-res$table; df<-data.frame(gene=target,retained=target %in% rownames(alltab),logFC=NA_real_,logCPM=NA_real_,F=NA_real_,p=NA_real_)
for(i in seq_along(target)) if(df$retained[i]) df[i,c('logFC','logCPM','F','p')]<-as.numeric(alltab[target[i],c('logFC','logCPM','F','PValue')])
df$bh_p_4<-p.adjust(df$p,method='BH',n=4)
write.csv(df,'outputs/stage6_gse167186_edger_candidate_results.csv',row.names=FALSE,na='')
cat('n samples:',sum(keep),'gene rows input:',nrow(raw),'retained:',sum(ok),'\n')
cat('normalization factor range:',range(y$samples$norm.factors),'\n')
print(df,row.names=FALSE);cat('edgeR:',as.character(packageVersion('edgeR')),'limma:',as.character(packageVersion('limma')),'statmod:',as.character(packageVersion('statmod')),'\n')
