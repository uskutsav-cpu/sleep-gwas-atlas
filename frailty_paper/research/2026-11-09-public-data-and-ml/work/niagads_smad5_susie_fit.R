.libPaths(c('work/stage5_Rlib', .libPaths()));library(susieR)
d<-read.csv('work/niagads_smad5_susie/aligned.csv');n<-nrow(d)
b<-readBin('work/niagads_smad5_susie/ld_f64.bin','double',n=n*n,size=8,endian='little');stopifnot(length(b)==n*n)
R<-matrix(b,n,n);rm(b);stopifnot(max(abs(R-t(R)))<1e-6,max(abs(diag(R)-1))<1e-6)
cat('Computing LD consistency diagnostics\n');flush.console()
e<-eigen(R,symmetric=TRUE);attr(R,'eigen')<-e
qdiag<-estimate_s_rss(d$qtl_beta_alt/d$qtl_se,R,n=737)
gdiag<-estimate_s_rss(d$gwas_beta_alt/d$gwas_se,R,n=403041)
diagnostic<-data.frame(trait=c('ROSMAP_exc_SMAD5','Mak_FI'),assumed_n=c(737,403041),n_variants=n,estimated_lambda=c(qdiag,gdiag),reference_n=503,min_eigenvalue=min(e$values),reference_rank_bound=502,package_version=as.character(packageVersion('susieR')))
write.csv(diagnostic,'outputs/stage6_niagads_smad5_susie_ld_diagnostics.csv',row.names=FALSE);print(diagnostic)
cat('Fitting QTL and FI\n');flush.console()
q<-susie_rss(z=d$qtl_beta_alt/d$qtl_se,R=R,n=737,L=10,max_iter=200,estimate_residual_variance=FALSE,verbose=FALSE)
g<-susie_rss(z=d$gwas_beta_alt/d$gwas_se,R=R,n=403041,L=10,max_iter=200,estimate_residual_variance=FALSE,verbose=FALSE)
stat<-function(x) if(is.null(x$sets$cs)) 0 else length(x$sets$cs)
purity<-function(x) if(is.null(x$sets$purity)) NA else min(x$sets$purity$min.abs.corr)
res<-data.frame(trait=c('ROSMAP_exc_SMAD5','Mak_FI'),converged=c(q$converged,g$converged),niter=c(q$niter,g$niter),n_credible_sets=c(stat(q),stat(g)),min_abs_corr=c(purity(q),purity(g)))
saveRDS(list(qtl=q,fi=g),'work/niagads_smad5_susie/fits.rds');write.csv(res,'outputs/stage6_niagads_smad5_susie_fit.csv',row.names=FALSE);print(res)
